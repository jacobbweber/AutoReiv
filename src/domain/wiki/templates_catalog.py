def slugify(text: str) -> str:
    """Convert text to clean snake_case filename slug."""
    s = text.strip().lower()
    s = _SLUG_CLEAN_PATTERN.sub("_", s).strip("_")
    return s[:80] or f"note_{int(dt.datetime.now().timestamp())}"


